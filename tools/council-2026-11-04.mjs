const zai = await ZAI.create();
for (const p of PERSONAS) {
  process.stdout.write(`→ ${p.file} … `);
  let ok = false;
  for (let attempt = 1; attempt <= 3 && !ok; attempt++) {
    try {
      const completion = await zai.chat.completions.create({
        messages: [
          { role: 'assistant', content: p.system },
          { role: 'user', content: p.user },
        ],
        thinking: { type: 'disabled' },
      });
      const text = completion.choices[0]?.message?.content ?? '';
      if (!text.trim()) throw new Error('пустой ответ');
      writeFileSync(path.join(OUT, p.file), text, 'utf8');
      console.log(`ok (${text.length} знаков)`);
      ok = true;
    } catch (e) {
      console.log(`попытка ${attempt} упала: ${e.message}`);
      await new Promise((r) => setTimeout(r, 1500 * attempt));
    }
  }
  if (!ok) console.log(`!! ${p.file} — не удалось`);
}
console.log('done');
