def main() -> None:
    d = json.loads(SPECS.read_text(encoding="utf-8"))
    cards = d["y_cards"]["cards"]
    by_id = {c["id"]: c for c in cards}

    fixed = 0
    for yid, new_pov in POV_FIX.items():
        c = by_id.get(yid)
        if not c:
            raise SystemExit(f"FATAL: карта {yid} не найдена")
        comp = c.setdefault("components", {})
        old = comp.get("pov", "")
        # камера позы сохраняется хвостом, если pov был её копией
        cam_ref = ""
        if "камера позы" in old:
            cam_ref = " (" + old[old.index("(камера позы") + 1:].rstrip(")")
        elif old.strip():
            cam_ref = f" (было: {old[:60]}…)" if len(old) > 60 else f" (было: {old})"
        comp["pov"] = new_pov + cam_ref
        fixed += 1

    # закон в y_cards.law
    law = d["y_cards"].get("law", "")
    if "ЗАНЯТОСТЬ РУК" not in law:
        d["y_cards"]["law"] = law + LAW_ADDENDUM

    # changelog + version
    d.setdefault("changelog", []).append(CHANGELOG_ENTRY)
    d["version"] = "1.19.0"

    SPECS.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"OK: pov-якоря у {fixed} карт; закон «занятость рук» в y_cards.law; v1.19.0")


if __name__ == "__main__":
    main()
